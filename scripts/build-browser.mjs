#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
// Build Roj for the browser from browser/ and the GNOME-free parts of extension/:
//
//   browser/app/defaults.js         the settings schema, read from the GSettings
//                                   schema so both editions share keys and limits
//   docs/app/                       the web app (PWA) that GitHub Pages serves
//   build/browser/{chrome,firefox,safari}/   unpacked extensions
//   dist/roj-{chrome,firefox,safari}-VERSION.zip   store and download packages
//
//   node scripts/build-browser.mjs           everything
//   node scripts/build-browser.mjs --web     defaults.js and docs/app only (make web)
//   node scripts/build-browser.mjs --check   fail when defaults.js or docs/app is stale
import {execFileSync} from 'node:child_process';
import {cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'browser');
const EXT = join(ROOT, 'extension');
const check = process.argv.includes('--check');
const webOnly = check || process.argv.includes('--web');
const {VERSION} = await import(join(EXT, 'lib/constants.js'));

const NAME = 'Roj: Kurdish Calendar';
const DESCRIPTION = 'The Kurdish solar calendar with Gregorian, Persian and Islamic dates, Kurdish events and holidays, in Sorani, Kurmanji, English, Persian and Arabic.';
const GECKO_ID = 'roj@0xdolan.github.io';
// Files of extension/ the browser code imports, at the same paths.
const SHARED = [
    'lib/engine.js', 'lib/tsroj.js', 'lib/events.js', 'lib/ics.js', 'lib/i18n.js', 'lib/constants.js',
    'locale/ckb.js', 'locale/kmr.js', 'locale/fa.js', 'locale/ar.js',
    'data/events/kurdish.json',
];
const FONT_DIR = 'fonts';
const PAGES = ['popup.html', 'options.html', 'roj.css'];

let stale = 0;

function write(path, data) {
    let current = null;
    try {
        current = readFileSync(path);
    } catch {}
    const bytes = Buffer.isBuffer(data) ? data : Buffer.from(data);
    if (current?.equals(bytes))
        return;
    if (check) {
        console.error(`${relative(ROOT, path)} is out of date: run "make web"`);
        stale++;
        return;
    }
    mkdirSync(dirname(path), {recursive: true});
    writeFileSync(path, bytes);
    if (!path.startsWith(join(ROOT, 'build')))
        console.log(`wrote ${relative(ROOT, path)}`);
}

function walk(dir) {
    return readdirSync(dir).flatMap(name => {
        const path = join(dir, name);
        return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

// 1. The settings schema
function parseDefault(type, text) {
    switch (type) {
    case 's':
        return text.slice(1, -1).replace(/\\(.)/g, '$1');
    case 'b':
        return text === 'true';
    case 'i':
    case 'd':
        return Number(text);
    case 'ai':
        return JSON.parse(text);
    default:
        throw new Error(`unsupported schema type ${type}`);
    }
}

function schema() {
    const xml = readFileSync(join(EXT, 'schemas/org.gnome.shell.extensions.roj.gschema.xml'), 'utf8');
    const out = {};
    for (const [, name, type, body] of xml.matchAll(/<key name="([^"]+)" type="([^"]+)">([\s\S]*?)<\/key>/g)) {
        const spec = {type, default: parseDefault(type, /<default>([\s\S]*?)<\/default>/.exec(body)[1].trim())};
        const choices = [...body.matchAll(/<choice value="([^"]*)"\/>/g)].map(m => m[1]);
        if (choices.length)
            spec.choices = choices;
        const range = /<range min="([^"]+)" max="([^"]+)"\/>/.exec(body);
        if (range)
            spec.range = [Number(range[1]), Number(range[2])];
        out[name] = spec;
    }
    return out;
}

const defaults = `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/build-browser.mjs from
// extension/schemas/org.gnome.shell.extensions.roj.gschema.xml. Do not edit.

export const SCHEMA = ${JSON.stringify(schema(), null, 4)};
`;
write(join(SRC, 'app/defaults.js'), defaults);

// 2. The common file set: [published path, bytes]
function commonFiles() {
    const files = new Map();
    for (const page of PAGES)
        files.set(page, readFileSync(join(SRC, page)));
    for (const path of walk(join(SRC, 'app')))
        files.set(relative(SRC, path), readFileSync(path));
    for (const path of walk(join(SRC, 'icons')))
        files.set(relative(SRC, path), readFileSync(path));
    for (const file of SHARED)
        files.set(file, readFileSync(join(EXT, file)));
    for (const path of walk(join(EXT, FONT_DIR)))
        files.set(relative(EXT, path), readFileSync(path));
    return files;
}

// 3. The web app
const APP = join(ROOT, 'docs/app');

function webApp() {
    const files = commonFiles();
    const head = [
        `<meta name="description" content="${DESCRIPTION}">`,
        '<meta name="theme-color" content="#F5CD0E">',
        '<link rel="manifest" href="manifest.webmanifest">',
        '<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">',
        '<link rel="icon" href="icons/roj.svg" type="image/svg+xml">',
        '<meta name="apple-mobile-web-app-title" content="Roj">',
    ].join('\n');
    const popup = files.get('popup.html').toString()
        .replace('<!--app-head-->', head)
        .replace('class="roj-popup-page"', 'class="roj-app"')
        .replace('<!--app-bar-->', '<div class="roj-app-bar"><button type="button" id="install" hidden></button></div>');
    files.delete('popup.html');
    files.set('index.html', popup);
    files.set('options.html', files.get('options.html').toString().replace('<!--app-head-->', head).replace('href="popup.html"', 'href="./"'));
    files.set('manifest.webmanifest', `${JSON.stringify({
        name: NAME,
        short_name: 'Roj',
        description: DESCRIPTION,
        id: './',
        start_url: './',
        scope: './',
        display: 'standalone',
        background_color: '#F8F8F8',
        theme_color: '#F5CD0E',
        categories: ['productivity', 'utilities', 'lifestyle'],
        icons: [
            {src: 'icons/roj-192.png', sizes: '192x192', type: 'image/png', purpose: 'any'},
            {src: 'icons/roj-512.png', sizes: '512x512', type: 'image/png', purpose: 'any'},
            {src: 'icons/roj-maskable-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable'},
            {src: 'icons/roj-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable'},
        ],
        shortcuts: [
            {name: 'Converter', url: 'options.html#converter', icons: [{src: 'icons/roj-96.png', sizes: '96x96'}]},
            {name: 'Settings', url: 'options.html#general', icons: [{src: 'icons/roj-96.png', sizes: '96x96'}]},
        ],
        screenshots: [
            {src: '../images/browser/store-1-popup.png', sizes: '1280x800', type: 'image/png', form_factor: 'wide', label: 'The Roj calendar'},
            {src: '../images/browser/store-3-converter.png', sizes: '1280x800', type: 'image/png', form_factor: 'wide', label: 'The date converter'},
        ],
    }, null, 2)}\n`);
    const cached = ['./', ...[...files.keys()].filter(p => p !== 'index.html' && !p.startsWith('fonts/licenses/'))].sort();
    // The cache name changes with the content, so a new build replaces the old copy.
    const hash = execFileSync('sha256sum', {input: Buffer.concat([...files.values()].map(v => Buffer.from(v)))}).toString().slice(0, 12);
    files.set('sw.js', `// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by scripts/build-browser.mjs. Keeps the Roj web app working offline.
const CACHE = 'roj-${VERSION}-${hash}';
const FILES = ${JSON.stringify(cached, null, 4)};

self.addEventListener('install', event => {
    event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
    event.waitUntil(caches.keys()
        .then(keys => Promise.all(keys.filter(k => k.startsWith('roj-') && k !== CACHE).map(k => caches.delete(k))))
        .then(() => self.clients.claim()));
});

self.addEventListener('fetch', event => {
    const url = new URL(event.request.url);
    if (event.request.method !== 'GET' || url.origin !== location.origin)
        return; // online calendars go straight to the network
    event.respondWith(caches.match(event.request, {ignoreSearch: true}).then(hit => hit ?? fetch(event.request)));
});
`);
    for (const [path, data] of files)
        write(join(APP, path), data);
    // Anything in docs/app that the build no longer makes.
    if (existsSync(APP)) {
        for (const path of walk(APP)) {
            const rel = relative(APP, path);
            if (files.has(rel))
                continue;
            if (check) {
                console.error(`docs/app/${rel} is no longer built: run "make web"`);
                stale++;
            } else {
                rmSync(path);
                console.log(`removed docs/app/${rel}`);
            }
        }
    }
}
webApp();

if (webOnly)
    process.exit(stale ? 1 : 0);

// 4. The extensions
function manifest(target) {
    const m = {
        manifest_version: 3,
        name: NAME,
        short_name: 'Roj',
        version: VERSION,
        description: DESCRIPTION,
        homepage_url: 'https://0xdolan.github.io/roj/',
        icons: {16: 'icons/roj-16.png', 32: 'icons/roj-32.png', 48: 'icons/roj-48.png', 96: 'icons/roj-96.png', 128: 'icons/roj-128.png'},
        action: {
            default_title: 'Roj',
            default_popup: 'popup.html',
            default_icon: {16: 'icons/roj-16.png', 32: 'icons/roj-32.png'},
        },
        options_ui: {page: 'options.html', open_in_tab: true},
        background: {service_worker: 'background.js', type: 'module'},
        permissions: ['storage', 'alarms'],
        optional_host_permissions: ['https://*/*', 'http://*/*'],
        minimum_chrome_version: '116',
    };
    if (target === 'firefox') {
        delete m.minimum_chrome_version;
        m.background = {scripts: ['background.js'], type: 'module'};
        m.browser_specific_settings = {
            gecko: {id: GECKO_ID, strict_min_version: '140.0', data_collection_permissions: {required: ['none']}},
            gecko_android: {strict_min_version: '142.0'},
        };
    }
    if (target === 'safari') {
        delete m.minimum_chrome_version;
        m.browser_specific_settings = {safari: {strict_min_version: '16.4'}};
    }
    return `${JSON.stringify(m, null, 2)}\n`;
}

const files = commonFiles();
files.set('background.js', readFileSync(join(SRC, 'background.js')));
mkdirSync(join(ROOT, 'dist'), {recursive: true});
for (const target of ['chrome', 'firefox', 'safari']) {
    const out = join(ROOT, 'build/browser', target);
    rmSync(out, {recursive: true, force: true});
    for (const [path, data] of files)
        write(join(out, path), data);
    write(join(out, 'manifest.json'), manifest(target));
    write(join(out, 'LICENSE'), readFileSync(join(ROOT, 'LICENSE')));
    const zip = join(ROOT, 'dist', `roj-${target}-${VERSION}.zip`);
    rmSync(zip, {force: true});
    execFileSync('zip', ['-qrX', zip, '.'], {cwd: out});
    console.log(`wrote ${relative(ROOT, zip)}`);
}
cpSync(join(ROOT, 'dist', `roj-firefox-${VERSION}.zip`), join(ROOT, 'dist', `roj-firefox-${VERSION}.xpi`));
process.exit(stale ? 1 : 0);
